  versions: function () {
    return Object.keys(window.TEXTBOOK);
  },
  subjects: function (ver) {
    var v = window.TEXTBOOK[ver]; return v ? Object.keys(v) : [];
  },
  grades: function (ver, subj) {
    var v = window.TEXTBOOK[ver]; if (!v || !v[subj]) return [];
    return Object.keys(v[subj]);
  },
  semesters: function (ver, subj, grade) {
    var v = window.TEXTBOOK[ver]; if (!v || !v[subj] || !v[subj][grade]) return [];
    return Object.keys(v[subj][grade]);
  },
  units: function (ver, subj, grade, sem) {
    var v = window.TEXTBOOK[ver];
    if (!v || !v[subj] || !v[subj][grade] || !v[subj][grade][sem]) return [];
    return v[subj][grade][sem];
  },
  lessons: function (ver, subj, grade, sem, unitIdx) {
    var units = window.TB.units(ver, subj, grade, sem);
    var u = units[unitIdx];
    return u ? (u.l || []) : [];
  },
